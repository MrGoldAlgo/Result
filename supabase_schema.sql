-- Run this once in Supabase Dashboard -> SQL Editor.
-- Mr Gold Trading Portal V3 Free Edition

create table if not exists public.accounts (
  id bigint generated by default as identity primary key,
  name text not null,
  public_slug text not null unique,
  api_key_hash text not null unique,
  created_at timestamptz not null default now(),
  broker text,
  server text,
  login text,
  currency text not null default 'USD',
  account_type text not null default 'unknown'
);

create table if not exists public.snapshots (
  id bigint generated by default as identity primary key,
  account_id bigint not null references public.accounts(id) on delete cascade,
  ts timestamptz not null,
  balance double precision not null,
  equity double precision not null,
  margin double precision not null default 0,
  free_margin double precision not null default 0,
  floating_profit double precision not null default 0
);

create index if not exists ix_snapshots_account_ts on public.snapshots(account_id, ts);

create table if not exists public.trades (
  id bigint generated by default as identity primary key,
  account_id bigint not null references public.accounts(id) on delete cascade,
  deal_ticket text not null,
  position_id text,
  magic text not null default '0',
  unique_id text not null default 'Unassigned',
  strategy text not null default 'Unlabelled',
  symbol text not null,
  side text not null,
  volume double precision not null default 0,
  open_price double precision not null default 0,
  close_price double precision not null default 0,
  open_time timestamptz not null,
  close_time timestamptz not null,
  profit double precision not null default 0,
  commission double precision not null default 0,
  swap double precision not null default 0,
  fee double precision not null default 0,
  net_profit double precision not null default 0,
  comment text not null default '',
  unique(account_id, deal_ticket)
);

create index if not exists ix_trades_account_close on public.trades(account_id, close_time);
create index if not exists ix_trades_unique_id on public.trades(account_id, unique_id);
create index if not exists ix_trades_magic on public.trades(account_id, magic);
create index if not exists ix_trades_symbol on public.trades(account_id, symbol);

-- The website talks to Supabase only with the server-side service-role key.
-- Public browser clients never receive that key.
alter table public.accounts enable row level security;
alter table public.snapshots enable row level security;
alter table public.trades enable row level security;
